package com.example.labsystem.domain.order;

/**
 * Статус замовлення обладнання
 */
public enum OrderStatus {
    /**
     * Чернетка - студент ще формує замовлення
     */
    DRAFT,

    /**
     * Зарезервовано - замовлення відправлено, обладнання забронювано на 24 години
     */
    RESERVED,

    /**
     * Очікує погодження
     */
    PENDING,

    /**
     * Погоджено адміністратором/лаборантом
     */
    APPROVED,

    /**
     * Відхилено
     */
    REJECTED,

    /**
     * Готове до видачі
     */
    READY_FOR_PICKUP,

    /**
     * Видано студенту
     */
    ISSUED,

    /**
     * Повернено
     */
    RETURNED,

    /**
     * Скасовано
     */
    CANCELLED
}
