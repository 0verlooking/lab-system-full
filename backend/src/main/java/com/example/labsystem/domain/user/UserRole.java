package com.example.labsystem.domain.user;

/**
 * Ролі користувачів у системі
 */
public enum UserRole {
    /**
     * Адміністратор - повний доступ до системи
     */
    ADMIN,

    /**
     * Куратор - викладач, куратор групи
     * Може:
     * - Створювати групи
     * - Формувати запрошення
     * - Управляти користувачами в зоні відповідальності
     * - Погоджувати та переглядати проекти своїх студентів
     * - Коментувати проекти
     */
    CURATOR,

    /**
     * Лаборант - відповідальний за склад і видачу обладнання
     * Може:
     * - Управляти обладнанням
     * - Погоджувати заявки на видачу
     * - Погоджувати закупівлю
     * - Працювати з документообігом
     * - Переглядати базу пресетів
     */
    LABORANT,

    /**
     * Менеджер лабораторії (залишено для зворотної сумісності)
     * Еквівалент LABORANT
     */
    LAB_MANAGER,

    /**
     * Студент - основний користувач системи
     * Може:
     * - Створювати та редагувати свої проекти
     * - Переглядати публічні проекти
     * - Резервувати обладнання
     * - Створювати пресети
     * - Коментувати проекти
     */
    STUDENT
}
